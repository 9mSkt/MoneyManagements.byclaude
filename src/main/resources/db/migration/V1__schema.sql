-- Money Management schema. Written in the SQL subset shared by H2 (MODE=PostgreSQL) and PostgreSQL.
-- All money columns are NUMERIC(14,2); rates and units use more decimals.

CREATE TABLE import_batch (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_name  VARCHAR(200) NOT NULL,
    imported_at  TIMESTAMP    NOT NULL,
    summary      VARCHAR(4000)
);

CREATE TABLE category (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          VARCHAR(60)  NOT NULL UNIQUE,
    name_en       VARCHAR(100) NOT NULL,
    name_th       VARCHAR(100) NOT NULL,
    type          VARCHAR(20)  NOT NULL,   -- INCOME, EXPENSE, TRANSFER
    budget_group  VARCHAR(20),             -- FIXED, GAS, NECESSARY, SHOPPING, EAT, SAVING, INVESTMENT (null for income)
    sort_order    INT          NOT NULL DEFAULT 0,
    needs_review  BOOLEAN      NOT NULL DEFAULT FALSE,
    active        BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE account (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(100)  NOT NULL,
    type             VARCHAR(20)   NOT NULL,  -- WALLET, BANK, INVESTMENT, CREDIT
    opening_balance  NUMERIC(14,2) NOT NULL DEFAULT 0,
    active           BOOLEAN       NOT NULL DEFAULT TRUE
);

CREATE TABLE installment (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item             VARCHAR(200)  NOT NULL,
    full_price       NUMERIC(14,2) NOT NULL,
    monthly_amount   NUMERIC(14,2) NOT NULL,
    months           INT           NOT NULL,
    interest_percent NUMERIC(7,4)  NOT NULL DEFAULT 0,
    start_month      DATE          NOT NULL,  -- first day of the month of payment 1
    paid_count       INT           NOT NULL DEFAULT 0,
    category_id      BIGINT REFERENCES category(id),
    import_batch_id  BIGINT REFERENCES import_batch(id) ON DELETE CASCADE
);

CREATE TABLE transaction_record (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tx_date           DATE          NOT NULL,
    type              VARCHAR(20)   NOT NULL,  -- INCOME, EXPENSE, TRANSFER
    amount            NUMERIC(14,2) NOT NULL,
    category_id       BIGINT        NOT NULL REFERENCES category(id),
    account_id        BIGINT REFERENCES account(id),
    description       VARCHAR(200),
    note              VARCHAR(1000),
    tags              VARCHAR(300),
    installment_id    BIGINT REFERENCES installment(id) ON DELETE SET NULL,
    installment_no    INT,
    kpi_percent       NUMERIC(7,2),
    incentive_percent NUMERIC(7,2),
    import_batch_id   BIGINT REFERENCES import_batch(id) ON DELETE CASCADE,
    created_at        TIMESTAMP     NOT NULL
);
CREATE INDEX ix_tx_date ON transaction_record(tx_date);
CREATE INDEX ix_tx_category_date ON transaction_record(category_id, tx_date);

CREATE TABLE recurring_item (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(200)  NOT NULL,
    amount          NUMERIC(14,2) NOT NULL,
    day_of_month    INT           NOT NULL DEFAULT 1,
    category_id     BIGINT        NOT NULL REFERENCES category(id),
    account_id      BIGINT REFERENCES account(id),
    active          BOOLEAN       NOT NULL DEFAULT TRUE,
    import_batch_id BIGINT REFERENCES import_batch(id) ON DELETE CASCADE
);

CREATE TABLE budget_rule (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    budget_month    DATE          NOT NULL,  -- first day of month; rules apply from this month until a later one overrides
    kind            VARCHAR(10)   NOT NULL,  -- ACTUAL, GOAL
    budget_group    VARCHAR(20)   NOT NULL,
    percent         NUMERIC(7,2),
    fixed_amount    NUMERIC(14,2),
    import_batch_id BIGINT REFERENCES import_batch(id) ON DELETE CASCADE,
    CONSTRAINT uq_budget_rule UNIQUE (budget_month, kind, budget_group)
);

CREATE TABLE goal (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(200)  NOT NULL,
    target_amount   NUMERIC(14,2) NOT NULL,
    saved_amount    NUMERIC(14,2) NOT NULL DEFAULT 0,
    deadline        DATE,
    import_batch_id BIGINT REFERENCES import_batch(id) ON DELETE CASCADE
);

CREATE TABLE asset (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(100)   NOT NULL,
    type            VARCHAR(20)    NOT NULL,  -- MUTUAL_FUND, ETF, STOCK, GOLD
    currency        VARCHAR(3)     NOT NULL,  -- THB, USD
    current_price   NUMERIC(18,6),
    price_date      DATE,
    import_batch_id BIGINT REFERENCES import_batch(id) ON DELETE CASCADE
);

CREATE TABLE asset_trade (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id        BIGINT         NOT NULL REFERENCES asset(id) ON DELETE CASCADE,
    trade_date      DATE           NOT NULL,
    side            VARCHAR(4)     NOT NULL,  -- BUY, SELL
    amount          NUMERIC(14,2)  NOT NULL,  -- in the trade currency
    currency        VARCHAR(3)     NOT NULL,
    fx_rate         NUMERIC(12,6),            -- THB per unit of currency (null/1 for THB)
    price_per_unit  NUMERIC(18,6)  NOT NULL,
    units           NUMERIC(20,8)  NOT NULL,
    fee             NUMERIC(14,2)  NOT NULL DEFAULT 0
);

CREATE TABLE dividend (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id        BIGINT         NOT NULL REFERENCES asset(id) ON DELETE CASCADE,
    pay_date        DATE           NOT NULL,
    amount          NUMERIC(14,2)  NOT NULL,
    withholding_tax NUMERIC(14,2)  NOT NULL DEFAULT 0,
    currency        VARCHAR(3)     NOT NULL,
    fx_rate         NUMERIC(12,6)
);

CREATE TABLE tax_year (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tax_year        INT           NOT NULL UNIQUE,
    monthly_salary  NUMERIC(14,2) NOT NULL DEFAULT 0,
    bonus           NUMERIC(14,2) NOT NULL DEFAULT 0,
    other_income    NUMERIC(14,2) NOT NULL DEFAULT 0,
    import_batch_id BIGINT REFERENCES import_batch(id) ON DELETE CASCADE
);

CREATE TABLE tax_deduction (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tax_year_id BIGINT        NOT NULL REFERENCES tax_year(id) ON DELETE CASCADE,
    code        VARCHAR(40)   NOT NULL,  -- EXPENSE, PERSONAL, SOCIAL_SECURITY, PVD, LIFE_INSURANCE, RMF, SSF, THAI_ESG, OTHER
    label       VARCHAR(200),
    amount      NUMERIC(14,2) NOT NULL
);

CREATE TABLE tax_bracket (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    income_from NUMERIC(14,2) NOT NULL,
    income_to   NUMERIC(14,2),            -- null = no upper limit
    rate        NUMERIC(5,2)  NOT NULL    -- percent
);
