-- Phase 6: account balances typed in by the owner (history for net worth over time), a note on goals,
-- and a small key/value table for app state (e.g. when the daily Google Sheet copy last ran).

CREATE TABLE account_balance (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id    BIGINT        NOT NULL REFERENCES account(id) ON DELETE CASCADE,
    balance_date  DATE          NOT NULL,
    balance       NUMERIC(14,2) NOT NULL,   -- for a CREDIT account: the amount owed
    CONSTRAINT uq_account_balance UNIQUE (account_id, balance_date)
);

ALTER TABLE account ADD COLUMN note VARCHAR(300);
ALTER TABLE goal ADD COLUMN note VARCHAR(500);

CREATE TABLE app_setting (
    setting_key   VARCHAR(100)  NOT NULL PRIMARY KEY,
    setting_value VARCHAR(4000),
    updated_at    TIMESTAMP     NOT NULL
);
