-- Phase 4: prices and USD/THB rates typed in by the owner, kept as history for the value-over-time chart.

CREATE TABLE asset_price (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id    BIGINT        NOT NULL REFERENCES asset(id) ON DELETE CASCADE,
    price_date  DATE          NOT NULL,
    price       NUMERIC(18,6) NOT NULL,   -- NAV or price per unit, in the asset currency
    CONSTRAINT uq_asset_price UNIQUE (asset_id, price_date)
);

CREATE TABLE fx_rate (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    currency    VARCHAR(3)    NOT NULL,   -- e.g. USD
    rate_date   DATE          NOT NULL,
    rate        NUMERIC(12,6) NOT NULL,   -- THB per one unit of the currency
    CONSTRAINT uq_fx_rate UNIQUE (currency, rate_date)
);
CREATE INDEX ix_trade_asset_date ON asset_trade(asset_id, trade_date);
CREATE INDEX ix_dividend_asset ON dividend(asset_id, pay_date);
